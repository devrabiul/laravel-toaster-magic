/**
 * AI reference files for laravel-toaster-magic.
 *
 * The Agent Skill and the Laravel Boost guideline both describe the preset
 * catalogue. Writing that catalogue by hand would drift from the packs, so it
 * is generated here and verified in CI alongside the minified assets.
 *
 * The preset list comes from the shipped pack scripts themselves: each one is
 * run in a sandbox against a stub of `window.ToastMagicPresets`, so the names
 * are exactly what the browser registers. The recommended type for each preset
 * comes from the sources that already record it:
 *
 *   - the "Available presets" table in PRESETS.md (the hand-drawn presets)
 *   - the role column of build/presets/catalogue*.py (the badge presets)
 *
 * A preset with no recommended type in either place fails the build, so a new
 * preset cannot ship without one.
 *
 * Outputs:
 *   - resources/boost/skills/laravel-toaster-magic/references/presets.md (whole file)
 *   - the marked `packs` block in the skill's SKILL.md
 *   - the marked `packs` block in resources/boost/guidelines/core.blade.php
 *   - the `version` of the Claude Code and Antigravity plugin manifests, taken
 *     from package.json
 */
import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";
import vm from "node:vm";

const SKILL_DIR = "resources/boost/skills/laravel-toaster-magic";
const CATALOGUES = ["catalogue.py", "catalogue2.py", "catalogue3.py"];
const ROLE_TO_TYPE = { ok: "success", info: "info", warn: "warning", bad: "error" };

/** Run a pack script and return { name: { icon, anim } } for what it registers. */
async function loadPack(root, pack) {
    const path = join(root, `assets/js/presets/toast-magic-presets-${pack}.js`);
    const registered = {};
    const window = {
        ToastMagicPresets: {
            attrs: "", s2: "", s3: "", f2: "", f3: "",
            register(icons, presets, name) {
                if (name !== pack) {
                    throw new Error(`${path} registers as "${name}", expected "${pack}"`);
                }
                Object.assign(registered, presets);
            },
        },
    };

    vm.runInNewContext(await readFile(path, "utf8"), { window, console }, { filename: path });

    return registered;
}

/** Hand-drawn presets: description and type from the PRESETS.md table. */
async function documentedPresets(root) {
    const rows = {};
    const row = /^\| `([a-z0-9-]+)` \| (.+?) \| `[a-z0-9-]+` \| `(success|error|warning|info)` \|/;

    for (const line of (await readFile(join(root, "PRESETS.md"), "utf8")).split("\n")) {
        const match = row.exec(line);
        if (match && !rows[match[1]]) rows[match[1]] = { icon: match[2], type: match[3] };
    }

    return rows;
}

/** Badge presets: type from the role column of the build catalogues. */
async function cataloguedTypes(root) {
    const types = {};
    const row = /^\s*\("([a-z0-9-]+)",\s*"\w+",\s*(?:"\w+"|None),\s*"\w+",\s*"\w+",\s*"(ok|info|warn|bad)"/;

    for (const file of CATALOGUES) {
        for (const line of (await readFile(join(root, "build/presets", file), "utf8")).split("\n")) {
            const match = row.exec(line);
            if (match) types[match[1]] = ROLE_TO_TYPE[match[2]];
        }
    }

    return types;
}

/** `cartQty` -> "cart qty", `cpu_bang` -> "cpu + bang". */
function describeIcon(key) {
    return key
        .split("_")
        .map((part) => part.replace(/([a-z0-9])([A-Z])/g, "$1 $2").toLowerCase())
        .join(" + ");
}

/** Build { pack: [{ name, icon, type }] } in PACKS order, or throw listing every gap. */
async function catalogue(root, packs) {
    const documented = await documentedPresets(root);
    const catalogued = await cataloguedTypes(root);
    const result = {};
    const untyped = [];

    for (const pack of packs) {
        const registered = await loadPack(root, pack);

        result[pack] = Object.keys(registered).sort().map((name) => {
            const type = documented[name]?.type ?? catalogued[name];
            if (!type) untyped.push(`${pack}/${name}`);

            return {
                name,
                icon: documented[name]?.icon ?? describeIcon(String(registered[name].icon ?? "")),
                type,
            };
        });
    }

    if (untyped.length) {
        throw new Error(
            `No recommended type for ${untyped.length} preset(s): ${untyped.join(", ")}.\n` +
            "Add each one to the PRESETS.md \"Available presets\" table or to a build/presets catalogue."
        );
    }

    return result;
}

function presetsMarkdown(presets) {
    const lines = [
        "<!-- Generated by build/references.mjs. Run `npm run build` instead of editing this file. -->",
        "",
        "# Preset catalogue",
        "",
        "Every preset name, grouped by the pack that must be listed under `presets` in",
        "`config/laravel-toaster-magic.php` for it to render. A preset from a pack that",
        "is not enabled is dropped server-side and the toast falls back to its type icon.",
        "",
        "**Type** is the toast method the preset is designed for (`ToastMagic::success`,",
        "`::error`, …). It is a recommendation, not a restriction.",
        "",
        "Search this file by keyword (e.g. `cart`, `deploy`, `payment`) rather than reading it top to bottom.",
    ];

    for (const [pack, rows] of Object.entries(presets)) {
        lines.push("", `## \`${pack}\` (${rows.length})`, "", "| Preset | Icon | Type |", "|---|---|---|");
        for (const { name, icon, type } of rows) lines.push(`| \`${name}\` | ${icon} | \`${type}\` |`);
    }

    return lines.join("\n") + "\n";
}

function packSummary(presets) {
    const total = Object.values(presets).reduce((sum, rows) => sum + rows.length, 0);
    const packs = Object.entries(presets).map(([pack, rows]) => `\`${pack}\` (${rows.length})`);

    return `${total} presets in ${packs.length} packs: ${packs.join(", ")}.`;
}

/** Replace the text between a BEGIN/END marker pair, keeping the markers. */
function replaceBlock(source, path, begin, end, body) {
    const start = source.indexOf(begin);
    const stop = source.indexOf(end);

    if (start === -1 || stop === -1 || stop < start) {
        throw new Error(`${path} is missing its "${begin}" … "${end}" markers`);
    }

    return source.slice(0, start + begin.length) + "\n" + body + "\n" + source.slice(stop);
}

/**
 * Write (or, with checkOnly, verify) every generated reference.
 *
 * @returns {Promise<boolean>} true when something is missing or stale.
 */
export async function buildReferences({ root, packs, checkOnly }) {
    const presets = await catalogue(root, packs);
    const summary = packSummary(presets);
    const skill = join(SKILL_DIR, "SKILL.md");
    const guideline = "resources/boost/guidelines/core.blade.php";

    const { version } = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
    const withVersion = (current, path) => {
        if (!current) throw new Error(`${path} is missing — it is a hand-written manifest, not a generated file`);
        return JSON.stringify({ ...JSON.parse(current), version }, null, 2) + "\n";
    };

    const outputs = [
        [join(SKILL_DIR, "references/presets.md"), () => presetsMarkdown(presets)],
        // Agent plugin manifests carry the release version; package.json owns it.
        [".claude-plugin/plugin.json", withVersion],
        [".antigravity-plugin/plugin.json", withVersion],
        [skill, (current) => replaceBlock(current, skill,
            "<!-- BEGIN GENERATED: packs -->", "<!-- END GENERATED: packs -->", summary)],
        [guideline, (current) => replaceBlock(current, guideline,
            "{{-- BEGIN GENERATED: packs --}}", "{{-- END GENERATED: packs --}}", summary)],
    ];

    let failed = false;

    for (const [output, render] of outputs) {
        const path = join(root, output);
        const current = existsSync(path) ? await readFile(path, "utf8") : null;
        const expected = render(current ?? "", output);

        if (current === expected) {
            console.log(`ok     ${output} is up to date`);
            continue;
        }

        if (!checkOnly) {
            await writeFile(path, expected);
            console.log(`built  ${output}`);
            continue;
        }

        console.error(
            `${current === null ? "MISSING" : "STALE"}  ${output} — it does not match the preset packs or package.json.\n` +
            "       Run `npm run build` and commit the result."
        );
        failed = true;
    }

    return failed;
}
